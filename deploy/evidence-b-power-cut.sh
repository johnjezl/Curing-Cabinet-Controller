#!/usr/bin/env bash
# Power cut capture. A labctl MCP power cycle is needed, which a shell cannot do, so
# this holds .rig/lock, sets the rig up, writes .rig/power-cut-ready, and waits for the
# rig to return with a new boot ID. Usage: evidence-b-power-cut.sh <label>
set -u
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RIG="$ROOT/deploy/rig.sh"
OUT="$ROOT/evidence/b/static-power-cut-${1:?usage: evidence-b-power-cut.sh <label>}.txt"
cd "$ROOT" || exit 1
SP=/tmp/claude-1000/-home-john-projects-Curing-Cabinet-Controller--claude-worktrees-bridge-cse-014Q9arxsNRyixQaUNwLct8J/b4f63687-8409-5247-bdf7-bd66d4506c04/scratchpad
if ! command -v go >/dev/null 2>&1 && [ -x "$SP/go/bin/go" ]; then PATH="$SP/go/bin:$PATH"; fi
export GOCACHE="${GOCACHE:-$ROOT/.rig/gocache}" GOPATH="${GOPATH:-$ROOT/.rig/gopath}"
exec 9>"$ROOT/.rig/lock"
flock -w 1800 9 || exit 75
export RIG_LOCK_HELD=1
HOST="${RIG_HOST:-192.168.4.142}"
{
  echo "# power cut through the labctl MCP tool. Not regenerated by evidence-b.sh. Label: $1"
  date -u
  echo "== combined source hash"; find internal/drivers internal/hal cmd/hwcheck cmd/curing-outputd cmd/fbshot deploy -type f | LC_ALL=C sort | xargs sha256sum | sha256sum
  "$RIG" service-stop
  "$RIG" hashes
  "$RIG" power-cut-before
  old=$(ssh -o BatchMode=yes -o ConnectTimeout=8 -o UserKnownHostsFile="$ROOT/.rig/known_hosts" "john@$HOST" cat /proc/sys/kernel/random/boot_id)
  ping -D -i 0.2 -W 1 "$HOST" >"$ROOT/.rig/power-cut-ping" 2>&1 &
  pingpid=$!
  touch "$ROOT/.rig/power-cut-ready"
  while :; do
    id=$(ssh -o BatchMode=yes -o ConnectTimeout=3 -o UserKnownHostsFile="$ROOT/.rig/known_hosts" "john@$HOST" cat /proc/sys/kernel/random/boot_id 2>/dev/null || true)
    if [ -n "$id" ] && [ "$id" != "$old" ]; then break; fi
    sleep 1
  done
  kill "$pingpid" 2>/dev/null
  # The last reply before the first gap in the ping sequence marks the cut.
  last=$(awk -F'[][]' '/bytes from/ {t=$2; split($3,a,"icmp_seq="); split(a[2],b," "); s=b[1]; if (ps && s>ps+5) {print pt; exit} pt=t; ps=s}' "$ROOT/.rig/power-cut-ping")
  echo "last_ping_before_gap=$last"
  sleep 20
  "$RIG" power-cut-after "$last"
  "$RIG" sudo-check
  "$RIG" hwstate
} >"$OUT" 2>&1
rm -f "$ROOT/.rig/power-cut-ready" "$ROOT/.rig/power-cut-ping"
echo "wrote $OUT"
